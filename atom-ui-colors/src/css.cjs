'use strict';
const SCOPE = '.monaco-workbench:not(.hc-black):not(.hc-light)';
const {resolveColors} = require('./icons.cjs');
const validId = id => /^[a-zA-Z][a-zA-Z0-9_.-]*$/.test(id);
function validateColors(colors) {
  if (!colors || typeof colors !== 'object' || Array.isArray(colors)) throw new Error('Colors must be an object.');
  for (const [id,color] of Object.entries(colors)) {
    if (!validId(id) || !/^#[0-9a-f]{6}$/i.test(color)) throw new Error(`Invalid icon/color: ${id}`);
  }
}
function renderCSS(palette, { colors = {}, viewColors = {}, aliases = {}, detectedViews = {}, resources = [], token = 'preview' } = {}) {
  validateColors(palette); validateColors(colors); validateColors(viewColors);
  if (!/^[a-zA-Z0-9-]+$/.test(token)) throw new Error('Invalid style token');
  let css = `/* ATOM-UI-COLORS:BEGIN ${token} */\n/* Native icon shapes and metrics are preserved. Generated by Atom UI Colors. */\n`;
  // Color the glyph itself, never its label or badges. A direct pseudo-element
  // color also survives parent hover colors marked !important by Modern UI.
  const enabled = ':not(.disabled):not([aria-disabled="true"]):not(.disabled *):not([aria-disabled="true"] *)';
  const contexts = [
    `${SCOPE} `,
    `${SCOPE}.modern-ui .activitybar>.content:not(.dragged-over):not(.dragged-over-head):not(.dragged-over-tail) :not(.monaco-menu)>.monaco-action-bar .action-item:not(.checked):hover `,
    `${SCOPE}.modern-ui-tabs .pane-composite-part>:is(.title,.header-or-footer)>.composite-bar-container>.composite-bar>.monaco-action-bar .action-item.icon:not(.checked):not(:active):hover> `,
  ];
  // Resolve fallback tokens from the current theme rather than a hard-coded
  // gray or hover-sensitive inheritance. Theme changes update CSS variables.
  const fallback = 'var(--atom-ui-colors-fallback, var(--vscode-icon-foreground, var(--vscode-foreground)))';
  css += `${SCOPE} :where(.activitybar,.activitybar2,.global-activity) { --atom-ui-colors-fallback: var(--vscode-activityBar-inactiveForeground, var(--vscode-activityBar-foreground, var(--vscode-icon-foreground, var(--vscode-foreground)))); }\n`;
  css += `${SCOPE} :where(.pane-composite-part .composite-bar) { --atom-ui-colors-fallback: var(--vscode-panelTitle-inactiveForeground, var(--vscode-icon-foreground, var(--vscode-foreground))); }\n`;
  css += `${SCOPE} :where(.part.statusbar) { --atom-ui-colors-fallback: var(--vscode-statusBar-foreground, var(--vscode-foreground)); }\n`;
  css += `${SCOPE} :where(.part.statusbar.debugging) { --atom-ui-colors-fallback: var(--vscode-statusBar-debuggingForeground, var(--vscode-statusBar-foreground, var(--vscode-foreground))); }\n`;
  css += `${SCOPE} :where(.part.statusbar.no-folder-workspace) { --atom-ui-colors-fallback: var(--vscode-statusBar-noFolderForeground, var(--vscode-statusBar-foreground, var(--vscode-foreground))); }\n`;
  css += `${SCOPE} :where(.monaco-button) { --atom-ui-colors-fallback: var(--vscode-button-foreground, var(--vscode-foreground)); }\n`;
  css += `${SCOPE} :where(.monaco-button.secondary) { --atom-ui-colors-fallback: var(--vscode-button-secondaryForeground, var(--vscode-button-foreground, var(--vscode-foreground))); }\n`;
  css += `${SCOPE} :where(.monaco-menu) { --atom-ui-colors-fallback: var(--vscode-menu-foreground, var(--vscode-foreground)); }\n`;
  const glyph = `.codicon:not(.file-icon):not(.folder-icon)${enabled}::before`;
  css += `${contexts.map(context => context + glyph).join(',\n')} { color: ${fallback} !important; }\n`;
  css += `${contexts.map(context => context + `.action-label.uri-icon${enabled}`).join(',\n')} { background-color: ${fallback} !important; }\n`;
  const groups = new Map();
  for (const [id,color] of Object.entries(resolveColors(palette, aliases, colors))) {
    if (!validId(id)) continue;
    if (!groups.has(color)) groups.set(color,[]);
    for (const context of contexts) groups.get(color).push(`${context}.codicon.codicon-${id}:not(.file-icon):not(.folder-icon)${enabled}::before`);
  }
  for (const [color, selectors] of groups) css += `${selectors.join(',\n')} { color: ${color} !important; }\n`;
  // More specific IDs follow prefixes (e.g. foo-bar follows foo), so URI-mask
  // class prefix matching cannot let a shorter view ID override a longer one.
  for (const [id,detected] of Object.entries({...detectedViews,...viewColors}).sort(([a],[b])=>a.length-b.length)) {
    if (!validId(id) || (detected !== null && !/^#[0-9a-f]{6}$/i.test(detected))) throw new Error(`Invalid detected icon/color: ${id}`);
    const color = detected || fallback;
    // VS Code generates activity-<view ID>-<digest> classes for URI masks.
    // Manifest view IDs are registered as workbench.view.extension.<id>.
    const normalized=id.replaceAll('.','-');
    const registered=id.startsWith('workbench.view.extension.')?normalized:`workbench-view-extension-${normalized}`;
    const identity = `.action-label.uri-icon:is([class*="activity-${registered}-"],[class*="activity-${normalized}-"],[id="${id}"],[id="workbench.view.extension.${id}"])${enabled}`;
    css += `${contexts.map(context=>context+identity).join(',\n')} { background-color: ${color} !important; }\n`;
  }
  for (const resource of resources) {
    if (!resource || typeof resource.path!=='string' || typeof resource.url!=='string'
      || !/^(?:vscode-file:\/\/vscode-app\/|data:image\/svg\+xml;base64,)/.test(resource.url)
      || (resource.color!==null && !/^#[0-9a-f]{6}$/i.test(resource.color))) throw new Error('Invalid SVG resource.');
    // Match VS Code's inline resource URL, never titles or translated labels.
    // These are dedicated image elements; menu labels and file/folder icons are
    // deliberately excluded so a mask cannot clip text or a file icon theme.
    const encoded=encodeURI(resource.path).replaceAll('#','%23').replaceAll('?','%3F');
    const paths=[...new Set([encoded,encodeURIComponent(resource.path)])];
    // Include a URL delimiter so icon.svg cannot match icon.svg-other.svg.
    const attributes=paths.flatMap(value=>['"',"'",')','&','?'].map(end=>`[style*=${JSON.stringify(value+end)}${resource.ignoreCase?' i':''}]`)).join(',');
    const identity=`:is(.action-label.icon,.custom-view-tree-node-item-icon,.monaco-icon-label-iconpath,.quick-input-list-icon):not(.monaco-menu *):not(.file-icon):not(.folder-icon):is(${attributes})${enabled}`;
    css += `${contexts.map(context=>context+identity).join(',\n')} { background-image: none !important; mask-image: url(${JSON.stringify(resource.url)}) !important; mask-mode: alpha !important; mask-repeat: no-repeat !important; mask-origin: padding-box !important; mask-position: center !important; mask-size: contain !important; background-color: ${resource.color || fallback} !important; }\n`;
    // Native toolbar images are 16px wide even when padding makes the button
    // 22/24px. `contain` would enlarge the drawing to the button's whole box.
    // One size value keeps non-square SVGs at their original aspect ratio.
    const fixedSize=`${identity}:is(.action-label.icon,.custom-view-tree-node-item-icon,.quick-input-list-icon)`;
    css += `${contexts.map(context=>context+fixedSize).join(',\n')} { mask-size: 16px !important; }\n`;
    const leftAligned=`${identity}:is(.custom-view-tree-node-item-icon,.quick-input-list-icon)`;
    css += `${contexts.map(context=>context+leftAligned).join(',\n')} { mask-position: left center !important; }\n`;
  }
  return css + `/* ATOM-UI-COLORS:END ${token} */\n`;
}
function stripStyles(html, token) {
  if (token && !/^[a-zA-Z0-9-]+$/.test(token)) throw new Error('Invalid style token');
  const matchToken = token || '[a-zA-Z0-9-]+';
  return html.replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, style => {
    const pattern = new RegExp(`/\\* ATOM-UI-COLORS:BEGIN (${matchToken}) \\*/[\\s\\S]*?/\\* ATOM-UI-COLORS:END \\1 \\*/\\r?\\n?`, 'g');
    const stripped = style.replace(pattern,'');
    if(stripped===style) return style;
    return /^<style\b[^>]*>\s*<\/style>$/i.test(stripped) ? '' : stripped;
  });
}
module.exports = {renderCSS, stripStyles, validateColors};
